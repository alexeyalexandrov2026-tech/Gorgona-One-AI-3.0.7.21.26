#!/usr/bin/env node
// Generates the Android app's translated strings from android/strings.json.
//
//   node android/scripts/build-strings.mjs           write the strings.xml files
//   node android/scripts/build-strings.mjs --check   fail if they are out of date
//
// Output: android/app/src/main/res/values[-<language>]/strings.xml
//
// android/strings.json carries every translation itself. The words are the
// iPhone app's (ios/strings.json), which takes most of them from the
// website, so the three never use different words for the same thing.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..');
const output = path.join(repo, 'android', 'app', 'src', 'main', 'res');

// Site language code -> the resource folder Android expects. Android still
// files Hebrew under its retired code.
const ANDROID_QUALIFIER = { he: 'iw' };

const { SUPPORTED_LANGUAGES, DEFAULT_LANGUAGE } = await import(
  pathToFileURL(path.join(repo, 'lib', 'languages.js')).href
);
const languages = SUPPORTED_LANGUAGES.map((language) => language.code);
const fallback = DEFAULT_LANGUAGE || 'en';

const manifest = JSON.parse(fs.readFileSync(path.join(repo, 'android', 'strings.json'), 'utf8'));
const table = manifest.strings;
const problems = [];

const placeholders = (text) => [...text.matchAll(/\{[a-z]+\}/g)].map((match) => match[0]).sort().join(' ');

for (const [key, entry] of Object.entries(table)) {
  if (!/^[a-z][a-z0-9_]*$/.test(key)) problems.push(`${key}: not a valid Android resource name`);
  if (key === 'locale_code') problems.push('locale_code is written by this script; remove it from strings.json');
  const english = entry[fallback];
  if (typeof english !== 'string' || !english.trim()) {
    problems.push(`${key}: no ${fallback} text`);
    continue;
  }
  for (const code of languages) {
    const value = entry[code];
    if (typeof value !== 'string' || !value.trim()) {
      problems.push(`${key}: no ${code} translation`);
    } else if (placeholders(value) !== placeholders(english)) {
      // "{count}" must survive translation, or the app shows the braces.
      problems.push(`${key}: ${code} has placeholders [${placeholders(value)}], ${fallback} has [${placeholders(english)}]`);
    }
  }
  for (const code of Object.keys(entry)) {
    if (!languages.includes(code)) problems.push(`${key}: "${code}" is not a language of the site`);
  }
}

// Android reads strings.xml with its own escapes on top of XML's.
function escape(text) {
  let value = text
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/\r?\n/g, '\\n')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
  if (/^[@?]/.test(value)) value = `\\${value}`;
  return value;
}

function render(code) {
  const header =
    '<?xml version="1.0" encoding="utf-8"?>\n' +
    '<!-- Generated by android/scripts/build-strings.mjs from android/strings.json. Do not edit. -->\n';
  // The site language these strings are written in, so the app can tell
  // which language Android actually picked (see MiamiElioTheme).
  const lines = [`    <string name="locale_code">${code}</string>`];
  for (const key of Object.keys(table).sort()) {
    const text = (table[key][code] ?? table[key][fallback] ?? '').trim();
    lines.push(`    <string name="${key}" formatted="false">${escape(text)}</string>`);
  }
  return `${header}<resources>\n${lines.join('\n')}\n</resources>\n`;
}

const files = new Map();
for (const code of languages) {
  const folder = code === fallback ? 'values' : `values-${ANDROID_QUALIFIER[code] || code}`;
  files.set(path.join(output, folder, 'strings.xml'), render(code));
}

if (problems.length) {
  console.error(`Strings need attention:\n  ${[...new Set(problems)].join('\n  ')}`);
  process.exit(1);
}

const count = Object.keys(table).length;
if (process.argv.includes('--check')) {
  const stale = [...files].filter(([file, content]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content);
  if (stale.length) {
    console.error(
      `Out of date - run \`node android/scripts/build-strings.mjs\`:\n  ${stale
        .map(([file]) => path.relative(repo, file))
        .join('\n  ')}`
    );
    process.exit(1);
  }
  console.log(`Android strings are up to date (${languages.length} languages, ${count} strings).`);
} else {
  for (const [file, content] of files) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
  console.log(`Wrote ${files.size} files (${languages.length} languages, ${count} strings) to ${path.relative(repo, output)}.`);
}
