"""Generate static additions and gallery updates from the reviewed inventory.

No network, database writes, inference, model calls or deployment. Requires Pillow.
Only visually reviewed vehicle mappings in decisions.json are eligible.
"""
from pathlib import Path
from PIL import Image, ImageChops, ImageStat
import json

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / 'docs/fleet-import'
read = lambda file: json.loads((DOCS / file).read_text(encoding='utf-8'))


def prepare():
    source, decisions, existing = read('source-inventory.json'), read('decisions.json'), read('existing-fleet.json')
    assets = {a['sourceUrl']: a for a in read('assets.json')['assets']}
    # Correct the historical snapshot only for matching, without rewriting the
    # evidence of the original error. Preserve original image bytes under an accurate path.
    rename = next(car for car in existing if car['slug'] == 'mercedes-g-class-white')
    rename.update(id='bmw-x5-white-brown', slug='bmw-x5-white-brown')
    rename['image'] = rename['image'].replace('/mercedes-g-class-white/', '/bmw-x5-white-brown/')
    rename['gallery'] = [p.replace('/mercedes-g-class-white/', '/bmw-x5-white-brown/') for p in rename['gallery']]
    original_folder = ROOT / 'public/images/rentals/mercedes-g-class-white'
    corrected_folder = ROOT / 'public/images/rentals/bmw-x5-white-brown'
    corrected_folder.mkdir(exist_ok=True)
    for original in original_folder.glob('*.jpg'):
        target = corrected_folder / original.name
        if target.exists() and target.read_bytes() != original.read_bytes():
            raise ValueError('Refusing to overwrite an unrelated corrected image')
        if not target.exists():
            target.write_bytes(original.read_bytes())
    cache = {}

    def reduced(file):
        if file not in cache:
            with Image.open(ROOT / 'public' / file.lstrip('/')) as image:
                cache[file] = image.convert('RGB').resize((64, 64), Image.Resampling.LANCZOS)
        return cache[file]

    def difference(a, b):
        return sum(ImageStat.Stat(ImageChops.difference(reduced(a), reduced(b))).mean) / 3

    additions, updates, equivalents, duplicate_review = [], {}, {}, []
    for row in decisions['vehicles']:
        if row['action'] not in ['add', 'merge']:
            continue
        vehicle = source['vehicles'][row['sourceIndex']]
        slug = row['targetSlug']
        photos = [assets[url]['path'] for url in vehicle['photoUrls']]
        if row['action'] == 'add':
            additions.append(dict(id=slug, slug=slug, title=row['title'], company='MIAMI ELIO', category=row.get('category', 'SUVs'), location='Miami',
                                  dailyPrice='On request', weeklyPrice='On request', monthlyPrice='On request',
                                  securityDeposit='On request', availability='Enquire', image=photos[0],
                                  thumbnail=assets[vehicle['photoUrls'][0]]['thumbnail'], gallery=photos,
                                  description=row['description'], featured=False))
            continue
        car = next(car for car in existing if car['slug'] == slug)
        gallery = list(dict.fromkeys([car['image'], *car['gallery']]))
        equivalents[slug] = {}
        for photo in photos:
            same = next((candidate for candidate in gallery if difference(photo, candidate) < 5), None)
            if same:
                equivalents[slug][photo] = same
                duplicate_review.append({'slug': slug, 'source': photo, 'existing': same,
                                         'meanAbsoluteDifference64px': round(difference(photo, same), 3)})
            else:
                gallery.append(photo)
        updates[slug] = {'gallery': gallery}
    if len(additions) != 13 or len(updates) != 10:
        raise ValueError('Reviewed inventory count changed')
    for name, value in [('gallery-equivalents.json', equivalents), ('photo-duplicate-review.json', duplicate_review)]:
        (DOCS / name).write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    output = '// Generated by scripts/import/prepare-miami.py from reviewed source mappings.\n'
    output += '// No external requests or source tariffs at runtime. Existing routes and descriptions are retained.\n'
    output += '/** @type {Array<{id:string,slug:string,title:string,company:string,category:string,location:string,dailyPrice:string,weeklyPrice:string,monthlyPrice:string,securityDeposit:string,availability:string,image:string,thumbnail:string,gallery:string[],description:string,featured:boolean}>} */\n'
    output += 'export const MIAMI_FLEET_ADDITIONS = ' + json.dumps(additions, ensure_ascii=False, indent=2) + ';\n\n'
    output += '/** @type {Record<string, {gallery:string[]}>} */\n'
    output += 'export const MIAMI_FLEET_UPDATES = ' + json.dumps(updates, ensure_ascii=False, indent=2) + ';\n'
    (ROOT / 'lib/miamiFleetImport.js').write_text(output, encoding='utf-8')
    print(json.dumps({'newVehicles': len(additions), 'existingGalleries': len(updates), 'equivalentPhotos': len(duplicate_review)}))


if __name__ == '__main__':
    prepare()
