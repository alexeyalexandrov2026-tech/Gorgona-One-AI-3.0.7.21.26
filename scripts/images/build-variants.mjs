// Writes the lighter WebP copies described in lib/responsiveImage.js.
//
//   node scripts/images/build-variants.mjs           write missing or outdated copies
//   node scripts/images/build-variants.mjs --check   change nothing; fail if anything is out of date
//
// Run it after adding or replacing a photo in public/images, and commit the
// result. Originals are never modified.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { variantWidths, variantPath } from '../../lib/responsiveImage.js';

const root = fileURLToPath(new URL('../../', import.meta.url));
const PUBLIC = path.join(root, 'public');
const MANIFEST = path.join(root, 'lib/imageManifest.js');
// Photo folders. Logos and small supplier artwork gain nothing from copies.
export const SOURCE_FOLDERS = ['images/rentals', 'images/home'];
const VARIANT_FOLDER = 'images/v';
const MIN_WIDTH = 600;
const QUALITY = 72;

export function listSources() {
  const files = [];
  const walk = (folder) => {
    for (const entry of fs.readdirSync(path.join(PUBLIC, folder), { withFileTypes: true })) {
      const relative = `${folder}/${entry.name}`;
      if (entry.isDirectory()) walk(relative);
      else if (/\.(jpe?g|png)$/i.test(entry.name)) files.push(`/${relative}`);
    }
  };
  for (const folder of SOURCE_FOLDERS) walk(folder);
  return files.sort();
}

export function manifestSource(widths) {
  const lines = Object.entries(widths).sort(([a], [b]) => (a < b ? -1 : 1)).map(([src, width]) => `  ${JSON.stringify(src)}: ${width}`);
  return `// Generated by scripts/images/build-variants.mjs. Do not edit by hand.\n// Original width, in pixels, of every photo that has lighter WebP copies.\nexport default {\n${lines.join(',\n')}\n};\n`;
}

async function main() {
  const check = process.argv.includes('--check');
  const { default: sharp } = await import('sharp');
  const widths = {};
  const expected = new Set();
  const stale = [];
  let written = 0;
  for (const src of listSources()) {
    const file = path.join(PUBLIC, src);
    // EXIF rotation is applied, so width is the width as displayed.
    const image = sharp(file).rotate();
    const { width, height, orientation } = await sharp(file).metadata();
    const shown = orientation >= 5 ? height : width;
    if (!shown || shown < MIN_WIDTH) continue;
    widths[src] = shown;
    for (const target of variantWidths(shown)) {
      const output = path.join(PUBLIC, variantPath(src, target));
      expected.add(output);
      if (fs.existsSync(output) && fs.statSync(output).mtimeMs >= fs.statSync(file).mtimeMs && !process.argv.includes('--force')) continue;
      if (check) { if (!fs.existsSync(output)) stale.push(variantPath(src, target)); continue; }
      fs.mkdirSync(path.dirname(output), { recursive: true });
      await image.clone().resize({ width: target, withoutEnlargement: true }).webp({ quality: QUALITY, effort: 5 }).toFile(output);
      written += 1;
    }
  }
  // Copies whose original is gone or was replaced by a different size.
  const orphans = [];
  const sweep = (folder) => {
    if (!fs.existsSync(folder)) return;
    for (const entry of fs.readdirSync(folder, { withFileTypes: true })) {
      const full = path.join(folder, entry.name);
      if (entry.isDirectory()) sweep(full);
      else if (!expected.has(full)) orphans.push(full);
    }
  };
  sweep(path.join(PUBLIC, VARIANT_FOLDER));
  const manifest = manifestSource(widths);
  const manifestCurrent = fs.existsSync(MANIFEST) && fs.readFileSync(MANIFEST, 'utf8') === manifest;
  if (check) {
    const problems = [...stale.map((file) => `missing ${file}`), ...orphans.map((file) => `unused ${path.relative(PUBLIC, file)}`), ...(manifestCurrent ? [] : ['lib/imageManifest.js is out of date'])];
    for (const problem of problems.slice(0, 20)) console.error(problem);
    if (problems.length) { console.error(`${problems.length} problem(s). Run: node scripts/images/build-variants.mjs`); process.exitCode = 1; }
    else console.log(`Image copies are up to date: ${Object.keys(widths).length} photos, ${expected.size} copies.`);
    return;
  }
  for (const file of orphans) fs.rmSync(file);
  if (!manifestCurrent) fs.writeFileSync(MANIFEST, manifest);
  console.log(`${Object.keys(widths).length} photos, ${expected.size} copies (${written} written, ${orphans.length} unused removed).`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
