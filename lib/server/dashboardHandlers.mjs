import { database, bookingInput, commandInput, requireKey, readBody, digest, json, failure, uuid, cursor, RequestError, REQUEST_STATES } from './dashboardCore.mjs';

const columns = 'id,item_slug,item_title,dates,status,kind,created_at,updated_at,version,response,assigned_partner_id,client_name,client_email,client_phone';
function scopeOf(url, user) {
  const scope = url.searchParams.get('scope') || 'customer';
  if (!['customer','partner','admin'].includes(scope)) throw new RequestError(400, 'Invalid scope');
  if (scope === 'admin' && user.role !== 'admin' || scope === 'partner' && !['partner','admin'].includes(user.role)) throw new RequestError(403, 'Access denied');
  return scope;
}
function accessQuery(scope, user) {
  return scope === 'customer' ? '&customer_user_id=eq.' + user.id : scope === 'partner' ? '&assigned_partner_id=eq.' + user.id : '';
}
function safeRow(row, scope) {
  const { client_email, client_phone, ...safe } = row;
  return scope === 'customer' ? safe : row;
}

export function dashboardHandlers(env, fetcher = fetch) {
  const guarded = fn => async (...args) => { try { return await fn(...args); } catch (error) { return failure(error); } };
  return {
    legacyNotify: guarded(async request => {
      await database(env,fetcher).identity(request);
      throw new RequestError(410,'Notifications are generated by saved events');
    }),
    book: guarded(async request => {
      const key = requireKey(request);
      const input = bookingInput(await readBody(request));
      const db = database(env, fetcher), user = await db.identity(request, true);
      if (!env.BOOKING_RATE_SECRET || env.BOOKING_RATE_SECRET.length < 32) throw new RequestError(503, 'Service unavailable');
      // CF-Connecting-IP is set by the site's Cloudflare ingress, never the body.
      const rate = await digest(request.headers.get('cf-connecting-ip') || 'unavailable', env.BOOKING_RATE_SECRET);
      const fingerprint = await digest(JSON.stringify([input, user?.id || null]));
      const receipt = await db.rpc('dashboard_submit', { p_key:key, p_fingerprint:fingerprint, p_rate:rate, p_user:user?.id || null, p_input:input });
      if (!receipt?.success || !uuid(receipt.bookingId)) throw new RequestError(503, 'Service unavailable');
      return json(receipt);
    }),
    list: guarded(async request => {
      const db = database(env, fetcher), user = await db.identity(request), url = new URL(request.url), scope = scopeOf(url, user);
      const state = url.searchParams.get('status');
      if (state && !REQUEST_STATES.includes(state)) throw new RequestError(400, 'Invalid status');
      const after = cursor(url.searchParams.get('cursor'));
      let query = '/rest/v1/bookings?select=' + columns + '&order=created_at.desc,id.desc&limit=26' + accessQuery(scope, user);
      if (state) query += '&status=eq.' + state;
      if (after) query += '&or=' + encodeURIComponent(`(created_at.lt.${after.at},and(created_at.eq.${after.at},id.lt.${after.id}))`);
      const rows = await db.call(query, { token:user.token });
      if (!Array.isArray(rows)) throw new RequestError(503, 'Service unavailable');
      const page = rows.slice(0,25), last = page.at(-1);
      return json({ requests:page.map(row => safeRow(row, scope)), nextCursor:rows.length > 25 ? btoa(last.created_at + '|' + last.id) : null });
    }),
    detail: guarded(async (request, id) => {
      if (!uuid(id)) throw new RequestError(404, 'Not found');
      const db = database(env, fetcher), user = await db.identity(request), scope = scopeOf(new URL(request.url), user);
      const rows = await db.call('/rest/v1/bookings?select=' + columns + '&id=eq.' + id + accessQuery(scope,user), { token:user.token });
      if (!rows?.[0]) throw new RequestError(404, 'Not found');
      const events = await db.call('/rest/v1/request_events?select=id,event_type,reply,created_at&booking_id=eq.' + id + '&order=created_at.asc,id.asc&limit=100', { token:user.token });
      return json({ request:safeRow(rows[0],scope), events });
    }),
    command: guarded(async (request, id) => {
      if (!uuid(id)) throw new RequestError(404, 'Not found');
      const key = requireKey(request), command = commandInput(await readBody(request));
      const db = database(env, fetcher), user = await db.identity(request);
      if (!['partner','admin'].includes(user.role) || command.action !== 'respond' && user.role !== 'admin') throw new RequestError(403, 'Access denied');
      const result = await db.rpc('dashboard_command', { p_actor:user.id, p_booking:id, p_key:key,
        p_fingerprint:await digest(JSON.stringify([id,command,user.id])), p_command:command });
      if (!result?.success) throw new RequestError(503, 'Service unavailable');
      return json(result);
    }),
    partners: guarded(async request => {
      const db = database(env, fetcher), user = await db.identity(request);
      if (user.role !== 'admin') throw new RequestError(403, 'Access denied');
      const partners = await db.call('/rest/v1/profiles?select=id,name,company_name&role=eq.partner&order=company_name.asc.nullslast,id.asc&limit=100', { token:user.token });
      return json({ partners });
    }),
    notifications: guarded(async request => {
      const db = database(env, fetcher), user = await db.identity(request);
      if (user.role !== 'admin') throw new RequestError(403, 'Access denied');
      const counts = await db.rpc('dashboard_delivery_status', { p_actor:user.id });
      return json({ counts, channels:{ telegram:!!(env.TELEGRAM_BOT_TOKEN && env.TELEGRAM_OWNER_CHAT_ID), email:!!(env.RESEND_API_KEY && env.ADMIN_EMAIL && env.NOTIFICATIONS_FROM_EMAIL) } });
    })
  };
}
