#!/usr/bin/env node
// Generates the app's translated strings from ios/strings.json and the
// website's own translations, so the app and the site never use two
// different words for the same thing.
//
//   node ios/scripts/build-strings.mjs           write the .strings files
//   node ios/scripts/build-strings.mjs --check   fail if they are out of date
//
// Output: ios/MiamiElio/Resources/<language>.lproj/{Localizable,InfoPlist}.strings

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..');
const output = path.join(repo, 'ios', 'MiamiElio', 'Resources');
const site = (relative) => import(pathToFileURL(path.join(repo, relative)).href);

// Site language code -> the folder name iOS expects.
const APPLE_CODE = { zh: 'zh-Hans' };

const { SUPPORTED_LANGUAGES } = await site('lib/languages.js');
const { getTranslation } = await site('lib/i18n.js');
const { STARTER_PROMPTS } = await site('lib/ai/conciergePrompts.js');
const languages = SUPPORTED_LANGUAGES.map((language) => language.code);
const catalogs = Object.fromEntries(
  await Promise.all(languages.map(async (code) => [code, (await site(`i18n/locales/${code}.js`)).default]))
);

const manifest = JSON.parse(fs.readFileSync(path.join(repo, 'ios', 'strings.json'), 'utf8'));
const problems = [];

const usable = (value) => typeof value === 'string' && value.trim().length > 0;
const readPath = (object, dotted) => dotted.split('.').reduce((node, key) => (node == null ? undefined : node[key]), object);

function fromSite(source, code) {
  if (source.lib) return readPath(getTranslation(code), source.lib);
  if (source.catalog) return catalogs[code]?.[source.catalog];
  if (Number.isInteger(source.starter)) return STARTER_PROMPTS[code]?.[source.starter];
  return undefined;
}

function resolve(key, entry, code) {
  if (entry.site) {
    const english = fromSite(entry.site, 'en');
    // The English copy written here documents what the screen says. If the
    // site has since reworded the phrase, a person should look at it.
    if (code === 'en' && english !== entry.en) {
      problems.push(`${key}: strings.json says ${JSON.stringify(entry.en)} but the site says ${JSON.stringify(english)}`);
    }
    const value = fromSite(entry.site, code);
    if (usable(value)) return value.trim();
    problems.push(`${key}: the site has no ${code} text for ${JSON.stringify(entry.site)}`);
    return entry.en;
  }
  if (code === 'en') return entry.en;
  const value = entry.translations?.[code];
  if (usable(value)) return value.trim();
  problems.push(`${key}: no ${code} translation in strings.json`);
  return entry.en;
}

const escape = (text) => text.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r?\n/g, '\\n');

function render(table, code) {
  const header = '/* Generated by ios/scripts/build-strings.mjs from ios/strings.json. Do not edit. */\n\n';
  const lines = Object.keys(table).sort().map((key) => `"${escape(key)}" = "${escape(resolve(key, table[key], code))}";`);
  return `${header}${lines.join('\n')}\n`;
}

const files = new Map();
for (const code of languages) {
  const folder = path.join(output, `${APPLE_CODE[code] || code}.lproj`);
  files.set(path.join(folder, 'Localizable.strings'), render(manifest.localizable, code));
  files.set(path.join(folder, 'InfoPlist.strings'), render(manifest.infoPlist, code));
}

if (problems.length) {
  console.error(`Strings need attention:\n  ${[...new Set(problems)].join('\n  ')}`);
  process.exit(1);
}

if (process.argv.includes('--check')) {
  const stale = [...files].filter(([file, content]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content);
  if (stale.length) {
    console.error(`Out of date - run \`node ios/scripts/build-strings.mjs\`:\n  ${stale.map(([file]) => path.relative(repo, file)).join('\n  ')}`);
    process.exit(1);
  }
  console.log(`iOS strings are up to date (${languages.length} languages).`);
} else {
  for (const [file, content] of files) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
  console.log(`Wrote ${files.size} files for ${languages.length} languages to ${path.relative(repo, output)}.`);
}
